// Command reference-docs renders the generated Provider and BackupClass
// manifests into a Markdown reference of every value users can set, and fails
// if one has no description. Descriptions are the Go doc comments of the types
// under definition/, which provider-sdk generate copies into the schemas.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	backupv1alpha1 "github.com/openeverest/openeverest/v2/api/backup/v1alpha1"
	common "github.com/openeverest/openeverest/v2/api/common/v1alpha1"
	corev1alpha1 "github.com/openeverest/openeverest/v2/api/core/v1alpha1"
	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"sigs.k8s.io/yaml"
)

func main() {
	definitionFile := flag.String("definition", "definition/provider.yaml", "provider definition, for the provider's name")
	providerFile := flag.String("provider", "charts/provider-cloudnative-pg/generated/provider-spec.yaml", "generated Provider manifest")
	backupClassDir := flag.String("backupclasses", "charts/provider-cloudnative-pg/generated/backupclasses", "directory of generated BackupClass manifests")
	out := flag.String("out", "docs/reference.md", "Markdown file to write")
	flag.Parse()

	if err := run(*definitionFile, *providerFile, *backupClassDir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "reference-docs:", err)
		os.Exit(1)
	}
}

func run(definitionFile, providerFile, backupClassDir, out string) error {
	var definition struct {
		Name string `json:"name"`
	}
	if err := readYAML(definitionFile, &definition); err != nil {
		return err
	}
	var provider corev1alpha1.Provider
	if err := readYAML(providerFile, &provider); err != nil {
		return err
	}
	if provider.Name == "" {
		provider.Name = definition.Name
	}
	files, err := filepath.Glob(filepath.Join(backupClassDir, "*.yaml"))
	if err != nil {
		return err
	}
	sort.Strings(files)
	var classes []backupv1alpha1.BackupClass
	for _, f := range files {
		var class backupv1alpha1.BackupClass
		if err := readYAML(f, &class); err != nil {
			return err
		}
		classes = append(classes, class)
	}

	doc, err := render(&provider, classes)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(out, doc, 0o644)
}

func readYAML(path string, into any) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := yaml.Unmarshal(data, into); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// section is one schema users fill in, such as an Instance component's parameters.
type section struct {
	title  string
	where  string
	schema *common.ParametersSchema
}

func sections(provider *corev1alpha1.Provider, classes []backupv1alpha1.BackupClass) []section {
	spec := provider.Spec
	var out []section
	out = append(out, section{"Instance parameters", "`spec.parameters` of an Instance", spec.ParametersSchema})
	for _, name := range sortedKeys(spec.Components) {
		c := spec.Components[name]
		out = append(out, section{
			fmt.Sprintf("Component %s (%s)", name, c.Type),
			fmt.Sprintf("`spec.components.%s.parameters` of an Instance", name),
			c.ParametersSchema,
		})
	}
	for _, name := range sortedKeys(spec.Topologies) {
		out = append(out, section{
			fmt.Sprintf("Topology %s", name),
			fmt.Sprintf("`spec.topology.parameters` of an Instance with `spec.topology.type: %s`", name),
			spec.Topologies[name].ParametersSchema,
		})
	}
	for _, class := range classes {
		out = append(out, section{
			fmt.Sprintf("BackupClass %s: backups", class.Name),
			"`spec.parameters` of a Backup, and `spec.backup.storages[].schedules[].parameters` of an Instance, " +
				fmt.Sprintf("with BackupClass `%s`", class.Name),
			&class.Spec.ParametersSchema,
		}, section{
			fmt.Sprintf("BackupClass %s: restores", class.Name),
			fmt.Sprintf("`spec.parameters` of a Restore from a backup of BackupClass `%s`", class.Name),
			&class.Spec.RestoreParametersSchema,
		})
		if pm := class.Spec.ProviderManaged; pm != nil {
			out = append(out, section{
				fmt.Sprintf("BackupClass %s: point-in-time recovery", class.Name),
				fmt.Sprintf("`spec.backup.storages[].pitr.parameters` of an Instance, with BackupClass `%s`", class.Name),
				pm.PITRParametersSchema,
			})
		}
	}
	return slices.DeleteFunc(out, func(s section) bool { return !hasFields(s.schema) })
}

func render(provider *corev1alpha1.Provider, classes []backupv1alpha1.BackupClass) ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	secs := sections(provider, classes)

	w("<!-- Generated by `make generate` (hack/reference-docs) from the doc comments of the\n")
	w("     types in definition/. Do not edit: change the comments and regenerate. -->\n\n")
	w("# %s reference\n\n", provider.Name)
	w("Every value users can set on an Instance, a Backup or a Restore of this provider, with its\n")
	w("type, constraints and description. The provider's admission webhook checks them against\n")
	w("the same schemas, which the `Provider` and `BackupClass` resources publish\n")
	w("(`kubectl get provider %s -o yaml`).\n\n", provider.Name)
	w("The fields of the Instance itself (`spec.version`, `spec.components.<name>.replicas`,\n")
	w("`resources`, `storage`, `schedulingPolicy`, `spec.dataSource`, ...) are OpenEverest's:\n")
	w("`kubectl explain instance.spec`.\n\n")

	w("- [Versions](#versions)\n- [Topologies](#topologies)\n")
	for _, s := range secs {
		w("- [%s](#%s)\n", s.title, anchor(s.title))
	}
	w("\n")

	renderVersions(w, provider.Spec)
	renderTopologies(w, provider.Spec)

	var missing []string
	for _, s := range secs {
		w("## %s\n\n", s.title)
		w("Set in %s.\n\n", s.where)
		missing = append(missing, renderFields(w, s.title, "", s.schema.OpenAPIV3Schema, 0)...)
	}

	if len(missing) > 0 {
		return nil, fmt.Errorf("no description for %d fields; add a doc comment to their Go field:\n  %s",
			len(missing), strings.Join(missing, "\n  "))
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n'), nil
}

func renderVersions(w func(string, ...any), spec corev1alpha1.ProviderSpec) {
	w("## Versions\n\n")
	w("`spec.version` of an Instance selects one of these releases (default `%s`).\n\n", spec.DefaultVersion)
	components := map[string]bool{}
	for _, v := range spec.Versions {
		for c := range v.Components {
			components[c] = true
		}
	}
	names := sortedKeys(components)
	w("| Version |")
	for _, c := range names {
		w(" %s |", c)
	}
	w("\n|---|")
	for range names {
		w("---|")
	}
	w("\n")
	for _, v := range spec.Versions {
		w("| `%s` |", v.Name)
		for _, c := range names {
			w(" %s |", componentVersion(spec, c, v.Components[c]))
		}
		w("\n")
	}
	w("\n")
}

// componentVersion shows a component's version with the image it runs.
func componentVersion(spec corev1alpha1.ProviderSpec, component, version string) string {
	if version == "" {
		return ""
	}
	if c, ok := spec.Components[component]; ok {
		for _, cv := range spec.ComponentTypes[c.Type].Versions {
			if cv.Version == version && cv.Image != "" {
				return fmt.Sprintf("%s (`%s`)", version, cv.Image)
			}
		}
	}
	return version
}

func renderTopologies(w func(string, ...any), spec corev1alpha1.ProviderSpec) {
	w("## Topologies\n\n")
	w("`spec.topology.type` of an Instance, and the components it has under `spec.components`.\n\n")
	w("| Topology | Component | Type | Optional |\n|---|---|---|---|\n")
	for _, name := range sortedKeys(spec.Topologies) {
		t := spec.Topologies[name]
		for _, c := range sortedKeys(t.Components) {
			typ := spec.Components[c].Type
			optional := ""
			if t.Components[c].Optional {
				optional = "yes"
			}
			w("| `%s` | `%s` | %s | %s |\n", name, c, typ, optional)
		}
	}
	w("\n")
}

// renderFields writes a heading per property of s, depth first, and returns
// the paths of the properties without a description.
func renderFields(w func(string, ...any), sectionTitle, prefix string, s *apiextensionsv1.JSONSchemaProps, depth int) []string {
	if s == nil {
		return nil
	}
	var missing []string
	for _, name := range sortedKeys(s.Properties) {
		prop := s.Properties[name]
		path := prefix + name
		level := "###"
		if depth > 0 {
			level = "####"
		}
		w("%s `%s`\n\n", level, path)
		w("%s\n\n", constraints(&prop, slices.Contains(s.Required, name)))
		if strings.TrimSpace(prop.Description) == "" {
			missing = append(missing, fmt.Sprintf("%s: %s", sectionTitle, path))
		} else {
			w("%s\n\n", markdown(prop.Description))
		}
		for _, rule := range prop.XValidations {
			w("- Rule: %s (`%s`)\n", escapeText(rule.Message), rule.Rule)
		}
		if len(prop.XValidations) > 0 {
			w("\n")
		}
		child, childPrefix := children(&prop, path)
		missing = append(missing, renderFields(w, sectionTitle, childPrefix, child, depth+1)...)
	}
	return missing
}

// children is the schema whose properties are nested under a field: the
// field's own, its array items' or its map values'.
func children(s *apiextensionsv1.JSONSchemaProps, path string) (*apiextensionsv1.JSONSchemaProps, string) {
	switch {
	case len(s.Properties) > 0:
		return s, path + "."
	case s.Items != nil && s.Items.Schema != nil:
		return children(s.Items.Schema, path+"[]")
	case s.AdditionalProperties != nil && s.AdditionalProperties.Schema != nil:
		return children(s.AdditionalProperties.Schema, path+".<key>")
	}
	return nil, ""
}

func typeName(s *apiextensionsv1.JSONSchemaProps) string {
	switch {
	case s.XIntOrString:
		return "integer or string"
	case s.Type == "array" && s.Items != nil && s.Items.Schema != nil:
		return "[]" + typeName(s.Items.Schema)
	case s.Type == "object" && s.AdditionalProperties != nil && s.AdditionalProperties.Schema != nil:
		return "map[string]" + typeName(s.AdditionalProperties.Schema)
	case s.Type == "object" && len(s.Properties) == 0 && s.XPreserveUnknownFields != nil && *s.XPreserveUnknownFields:
		return "object (any fields)"
	case s.Type == "" && len(s.AnyOf) > 0:
		var types []string
		for _, a := range s.AnyOf {
			types = append(types, typeName(&a))
		}
		return strings.Join(types, " or ")
	case s.Format != "":
		return s.Type + " (" + s.Format + ")"
	case s.Type == "":
		return "any"
	}
	return s.Type
}

func constraints(s *apiextensionsv1.JSONSchemaProps, required bool) string {
	parts := []string{"`" + typeName(s) + "`"}
	if required {
		parts = append(parts, "required")
	}
	if s.Default != nil {
		parts = append(parts, "default `"+string(s.Default.Raw)+"`")
	}
	if len(s.Enum) > 0 {
		var values []string
		for _, e := range s.Enum {
			values = append(values, "`"+strings.Trim(string(e.Raw), `"`)+"`")
		}
		parts = append(parts, "one of "+strings.Join(values, ", "))
	}
	if s.Minimum != nil {
		parts = append(parts, fmt.Sprintf("minimum %g", *s.Minimum))
	}
	if s.Maximum != nil {
		parts = append(parts, fmt.Sprintf("maximum %g", *s.Maximum))
	}
	if s.MinLength != nil {
		parts = append(parts, fmt.Sprintf("at least %d characters", *s.MinLength))
	}
	if s.MaxLength != nil {
		parts = append(parts, fmt.Sprintf("at most %d characters", *s.MaxLength))
	}
	if s.MinItems != nil {
		parts = append(parts, fmt.Sprintf("at least %d items", *s.MinItems))
	}
	if s.MaxItems != nil {
		parts = append(parts, fmt.Sprintf("at most %d items", *s.MaxItems))
	}
	if s.Pattern != "" {
		parts = append(parts, "pattern `"+s.Pattern+"`")
	}
	return strings.Join(parts, " · ")
}

// markdown turns a doc comment into Markdown, following Go doc comment
// conventions: indented lines after a blank line are code, "* " and "- "
// lines are list items (nested when indented), and other indented lines
// continue the line before. Text is escaped so that <instance> or pgaudit.*
// shows as written.
func markdown(text string) string {
	var out []string
	inCode, inList := false, false
	prevBlank := true
	for line := range strings.SplitSeq(text, "\n") {
		trimmed := strings.TrimSpace(line)
		indented := trimmed != "" && line != strings.TrimLeft(line, " \t")
		if inCode {
			if indented || trimmed == "" {
				out = append(out, codeLine(line))
				continue
			}
			out = append(trimTrailingBlank(out), "```", "")
			inCode = false
		}
		item, bullet := listItem(trimmed)
		switch {
		case trimmed == "":
			out = append(out, "")
			inList = false
		case indented && prevBlank && !bullet:
			out = append(out, "```text", codeLine(line))
			inCode = true
		case bullet && indented:
			out = append(out, "  - "+escapeText(item))
			inList = true
		case bullet:
			out = append(out, "- "+escapeText(item))
			inList = true
		case indented:
			out = append(out, "  "+escapeText(trimmed))
		default:
			if inList {
				// Ends the list rather than continuing its last item.
				out = append(out, "")
				inList = false
			}
			out = append(out, escapeText(line))
		}
		prevBlank = trimmed == ""
	}
	if inCode {
		out = append(trimTrailingBlank(out), "```")
	}
	return strings.TrimSpace(strings.Join(out, "\n"))
}

func listItem(line string) (string, bool) {
	for _, marker := range []string{"* ", "- "} {
		if item, ok := strings.CutPrefix(line, marker); ok {
			return item, true
		}
	}
	return "", false
}

func codeLine(line string) string {
	return strings.TrimPrefix(strings.TrimPrefix(line, "\t"), "  ")
}

func trimTrailingBlank(lines []string) []string {
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

// escapeText escapes Markdown and HTML outside of `code spans`.
func escapeText(line string) string {
	parts := strings.Split(line, "`")
	if len(parts)%2 == 0 {
		// An unpaired backtick: no code spans.
		return escapePlain(line)
	}
	for i := 0; i < len(parts); i += 2 {
		parts[i] = escapePlain(parts[i])
	}
	return strings.Join(parts, "`")
}

var plainEscaper = strings.NewReplacer(
	`\`, `\\`, "<", "&lt;", ">", "&gt;", "*", `\*`, "[", `\[`, "]", `\]`, "`", "\\`", "|", `\|`,
)

// escapePlain escapes text with no code spans, including a leading # that
// would turn the line into a heading.
func escapePlain(s string) string {
	s = plainEscaper.Replace(s)
	if strings.HasPrefix(strings.TrimLeft(s, " "), "#") {
		s = strings.Replace(s, "#", `\#`, 1)
	}
	return s
}

// anchor is GitHub's anchor of a heading.
func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		case r == ' ':
			b.WriteRune('-')
		}
	}
	return b.String()
}

func hasFields(s *common.ParametersSchema) bool {
	return s != nil && s.OpenAPIV3Schema != nil && len(s.OpenAPIV3Schema.Properties) > 0
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
